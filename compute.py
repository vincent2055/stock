def ma(c, n):
    return sum(c[:n]) / n

results = []
for s in stocks:
    c = s["closes"]
    ma5 = ma(c,5); ma10 = ma(c,10); ma20 = ma(c,20)
    price = s["price"]
    above5 = price > ma5
    above10 = price > ma10
    above20 = price > ma20
    # 趋势分 (均线位置分, 满分65)
    if above5 and above10 and above20:
        pos = "5/10/20上方"; trend65 = 65
    elif above5 and above10 and not above20:
        pos = "5/10上方"; trend65 = 55
    elif above20 and not (above5 and above10):
        pos = "20日线上"; trend65 = 45
    else:
        pos = "全线下方"; trend65 = 30
    # 止损价
    low20 = min(c[:20])
    if not above20:
        stop = round(low20, 2)
    elif above5 and above10:
        stop = round(ma10, 2)
    else:
        stop = round(ma20, 2)
    # 五维评分
    # 趋势(30)
    trend30 = {65:30, 55:24, 45:18, 30:12}[trend65]
    # 量价(20)
    up = s["chg"] > 0
    if up and s["vr"] >= 1: vol = 20
    elif up and s["vr"] < 1: vol = 15
    elif (not up) and s["vr"] < 1: vol = 12
    else: vol = 8
    # 强度(20)
    if s["chg"] > 5: st = 20
    elif s["chg"] > 2: st = 15
    elif s["chg"] > 0: st = 10
    else: st = 5
    # 板块(15)
    sc = s["sect_chg"]
    if s["is_etf"]: sec = 10
    elif sc > 0.5: sec = 15
    elif sc > -1.0: sec = 10
    else: sec = 5
    # 风险(15)
    dist = (price - stop) / stop * 100
    if dist > 5: risk = 15
    elif dist > 2: risk = 10
    else: risk = 5
    total = trend30 + vol + st + sec + risk
    # 持仓分级
    if s["chg"] > 2 and (above5 and above10 and above20):
        grade = "A"
    elif (above5 and above10 and above20) or (above20 and -2 <= s["chg"] <= 2):
        grade = "B"
    elif (not above20) and s["chg"] >= -2:
        grade = "C"
    else:
        grade = "D"
    results.append({
        "code": s["code"], "name": s["name"], "etf": s["is_etf"],
        "price": price, "chg": s["chg"],
        "ma5": round(ma5,3), "ma10": round(ma10,3), "ma20": round(ma20,3),
        "pos": pos, "trend65": trend65,
        "stop": stop, "dist": round(dist,1),
        "dims": {"trend": trend30, "vol": vol, "strength": st, "sector": sec, "risk": risk},
        "total": total, "grade": grade,
        "sector": s["sector"], "sect_chg": s["sect_chg"],
        "volume_ratio": s["vr"],
    })

# 排序：按综合评分降序
results.sort(key=lambda x: -x["total"])

out = {"stocks": results}
print(json.dumps(out, ensure_ascii=False, indent=1))

